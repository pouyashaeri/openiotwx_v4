-- CHORDS compatibility: a shared catalog of variables (parameters), a numeric
-- instrument id per station (what CHORDS devices put in `instrument_id=`), a
-- per-station switch to accept only the enabled variables, and linking a station
-- to an instrument on another CHORDS portal.

create table if not exists variables (
  shortname  text primary key check (shortname ~ '^[a-z][a-z0-9_]{0,39}$'),
  name       text not null,
  units      text not null default '',
  category   text not null default 'other',
  builtin    boolean not null default false,
  created_by text,
  created_at timestamptz not null default now()
);

insert into variables (shortname, name, units, category, builtin) values
  ('temp_c',            'Air temperature',      '°C',    'air',      true),
  ('humidity_pct',      'Relative humidity',    '%',     'air',      true),
  ('pressure_hpa',      'Pressure',             'hPa',   'air',      true),
  ('dewpoint_c',        'Dew point',            '°C',    'air',      true),
  ('rain_mm',           'Rain',                 'mm',    'water',    true),
  ('wind_ms',           'Wind speed',           'm/s',   'wind',     true),
  ('wind_gust_ms',      'Wind gust',            'm/s',   'wind',     true),
  ('wind_dir_deg',      'Wind direction',       '°',     'wind',     true),
  ('soil_moisture_pct', 'Soil moisture',        '%',     'soil',     true),
  ('soil_temp_c',       'Soil temperature',     '°C',    'soil',     true),
  ('pm25_ugm3',         'PM2.5',                'µg/m³', 'air quality', true),
  ('pm10_ugm3',         'PM10',                 'µg/m³', 'air quality', true),
