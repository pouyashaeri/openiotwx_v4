  ('rssi_dbm',          'Signal strength',      'dBm',   'device',   true)
on conflict (shortname) do nothing;

alter table stations add column if not exists chords_id integer generated by default as identity;
create unique index if not exists stations_chords_id_uq on stations (chords_id);

-- When true, uploads may only carry the variables enabled for the station.
alter table stations add column if not exists strict_metrics boolean not null default false;

-- 'device' = reports to us; 'chords' = pulled from another CHORDS portal.
-- remote = { portal, instrumentId, email, lastSync, nextSync, everyMin, lastError }  (no secrets)
-- remote_key = the portal API key, encrypted by the app; never selected into API responses.
alter table stations add column if not exists source text not null default 'device';
alter table stations add column if not exists remote jsonb;
alter table stations add column if not exists remote_key text;
